"""Final report (D-052): one page that summarises a finished run, built only from the run's own output files.

Nothing here is computed from the pack or hand-written: every number comes from decisions.jsonl, actions.jsonl,
control_log.jsonl, latency_report.json, data_quality_report.json, outcomes.jsonl, impact.json and the simulator report,
so an unseen replay day reports its own numbers.
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

from .impact import _pct, _pts, _verdict

# What each no-action code means (decision records carry the per-viewer detail).
NO_ACTION_MEANING = {
    "HOLDOUT": "holdout arm: decided as a shadow, nothing published (randomized comparison)",
    "STALE_TRIGGER": "offline-buffered or late app open: not a live visit, history only (D-006)",
    "SAME_SESSION": "second trigger of the same visit with nothing changed (D-039)",
    "DUPLICATE_IGNORED": "same trigger delivered again: no second decision or action (D-004)",
    "NO_GOAL": "no eligible measurable goal, including goals not repeated after a recent failure (D-013, D-051)",
    "PAGE_STILL_LIVE": "the page for this goal is still live: nothing new to show (D-033)",
    "DIALECT_UNKNOWN": "the app's dialect setting is missing or invalid: no page rather than a guess (D-009)",
    "DATA_STORE_UNAVAILABLE": "viewer data could not be read in time: generic page, no message or goal (D-036)",
}


def _jsonl(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def _json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def build_final(out: Path) -> str:
    out = Path(out)
    D = _jsonl(out / "decisions.jsonl")
    A = _jsonl(out / "actions.jsonl")
    C = _jsonl(out / "control_log.jsonl")
    O = _jsonl(out / "outcomes.jsonl")
    lat, imp = _json(out / "latency_report.json"), _json(out / "impact.json")
    quality = _json(out / "data_quality_report.json")
    sim = _json(out / "sim" / "simulator_report.json")

    status = Counter(d["status"] for d in D)
    arm_of = {d["decision_id"]: d.get("arm") for d in D}
    holdout_actions = sum(1 for a in A if arm_of.get(a.get("decision_id")) == "holdout")
    deliver = sorted(d["trigger"]["deliver_at"] for d in D if d.get("trigger", {}).get("deliver_at"))
    L = [
        "# Final report",
        "",
        (
            "Generated by `python -m ott_agent run` from this folder's own files; nothing in it is written by hand. "
            "Design: [ARCHITECTURE.md](../ARCHITECTURE.md). What was left out on purpose: "
            "[KNOWN_LIMITATIONS.md](../KNOWN_LIMITATIONS.md)."
        ),
        "",
        "## 1. What was run",
        "",
        f"- Replay window (trigger delivery): {deliver[0] if deliver else 'n/a'} to {deliver[-1] if deliver else 'n/a'}",
        (
            f"- Triggers: {len(D)} for {len({d.get('viewer_id') for d in D})} viewers; simulator seed "
            f"`{sim.get('seed', 'n/a')}`; model provider `{_provider(D)}`"
        ),
        f"- Rule versions: {json.dumps(D[0].get('config_versions', {}) if D else {}, ensure_ascii=False)}",
        "",
        "## 2. Decisions",
        "",
        "| Status | Decisions |",
        "|---|---|",
        *[f"| {k} | {v} |" for k, v in status.most_common()],
        "",
        (
            "**No-action reasons.** Every decision that published nothing has a reason code and a per-viewer explanation "
            "in `decisions.jsonl` (`no_action_reason`)."
        ),
        "",
        "| Reason | Decisions | Meaning |",
        "|---|---|---|",
    ]
    codes = Counter(d["no_action_reason"]["code"] for d in D if d.get("no_action_reason"))
    L += [f"| {k} | {v} | {NO_ACTION_MEANING.get(k, '')} |" for k, v in codes.most_common()]
    missing = sum(1 for d in D if d["status"] != "PUBLISHED" and not d.get("no_action_reason"))
    L += ["", f"Decisions that published nothing without a recorded reason: **{missing}**.", ""]
    L += _goals(D)
    L += _realtime(lat)
    L += _safety(D, A, sim, holdout_actions)
    L += _surprises(C, D)
    L += _traps(quality, imp)
    L += _outcomes(O)
    L += _impact(imp)
    L += [
        "## 10. Where to find the details",
        "",
        "| File | Contents |",
        "|---|---|",
        (
            "| `decisions.jsonl` | every decision: goal, action, dialect + conflicts, evidence + freshness, assumptions, "
            "checks, timing |"
        ),
        "| `actions.jsonl` | published actions (simulator schema) |",
        "| `viewer_state/<user>.json` | what each viewer's agent knew, decided, observed and learned |",
        "| `control_log.jsonl` | withdrawals, rule corrections, outages, reactions to live events |",
        "| `latency_report.json` | latency, budgets, bursts, model outcomes, fallbacks |",
        "| `data_quality_report.json` | data issues found, how each was handled and the tests that prove it |",
        "| `outcomes.jsonl` | goal verdicts and learning notes |",
        "| `impact_report.md` | agent arm vs holdout in full, misleading comparisons, pilot re-analysis |",
        "",
    ]
    return "\n".join(L)


def _provider(D) -> str:
    return next((d["model"]["provider"] for d in D if (d.get("model") or {}).get("provider")), "n/a")


def _goals(D) -> list[str]:
    fresh = [d for d in D if d["status"] in ("PUBLISHED", "NO_ACTION", "HOLDOUT_SHADOW")]
    by_arm = {arm: Counter((d.get("goal") or {}).get("goal_id") or "no goal" for d in fresh if d.get("arm") == arm)
              for arm in ("agent", "holdout")}  # fmt: skip
    goals = sorted(set(by_arm["agent"]) | set(by_arm["holdout"]))
    switched = Counter(d.get("arm") for d in fresh if "(D-051)" in ((d.get("goal") or {}).get("why") or ""))
    no_goal = Counter(
        d.get("arm") for d in fresh if not d.get("goal") and "(D-051)" in (d.get("goal_note") or "")
    )
    L = [
        "## 3. Goals chosen (live decisions)",
        "",
        "| Goal | Agent arm | Holdout (shadow) |",
        "|---|---|---|",
        *[f"| {g} | {by_arm['agent'][g]} | {by_arm['holdout'][g]} |" for g in goals],
        "",
        (
            "**Learning fed back (D-051):** live decisions where a goal had recently failed for the viewer (earlier pilot "
            "or our own judged goal) and would otherwise have been chosen. The same rule runs in both arms."
        ),
        "",
        "| | Agent arm | Holdout (shadow) |",
        "|---|---|---|",
        f"| Got the next eligible goal instead | {switched['agent']} | {switched['holdout']} |",
        f"| No other eligible goal: no goal, no action | {no_goal['agent']} | {no_goal['holdout']} |",
        "",
    ]
    return L


def _realtime(lat) -> list[str]:
    pages = lat.get("latency_s_published_pages", {})
    bursts = (lat.get("load") or {}).get("bursts", [])
    return [
        "## 4. Real time",
        "",
        "| | |",
        "|---|---|",
        (
            f"| Published pages: latency p50 / p95 / max | {pages.get('p50')} s / {pages.get('p95')} s / "
            f"{pages.get('max')} s |"
        ),
        f"| Decisions over 60 s | {lat.get('over_60s')} |",
        (
            f"| Max model / tool calls per decision | {lat.get('max_model_calls_per_decision')} / "
            f"{lat.get('max_tool_calls_per_decision')} |"
        ),
        f"| Model outcomes | {_kv(lat.get('model_outcomes', {}))} |",
        f"| Fallbacks used | {_kv(lat.get('fallbacks', {})) or 'none'} |",
        (
            f"| Traffic bursts noticed | {len(bursts)} (max queue {max((b['max_queue_s'] for b in bursts), default=0)} s)"
            " |"
        ),
        "",
    ]


def _safety(D, A, sim, holdout_actions) -> list[str]:
    verdicts = Counter((d.get("verifier") or {}).get("verdict") for d in D if d.get("verifier"))
    counts = sim.get("counts", {})
    return [
        "## 5. Verification and safety",
        "",
        "| | |",
        "|---|---|",
        f"| Independent verifier verdicts | {_kv(verdicts)} |",
        f"| Pack simulator: policy problems | **{sim.get('policy_problem_count', 'n/a')}** |",
        (
            f"| Home pages accepted by the simulator | {counts.get('home_page_accepted', 'n/a')} of "
            f"{sum(1 for a in A if a['type'] == 'home_page')} |"
        ),
        (
            f"| Messages published (push / WhatsApp) | {sum(1 for a in A if a['type'] == 'push')} / "
            f"{sum(1 for a in A if a['type'] == 'whatsapp')} |"
        ),
        f"| Actions for holdout viewers | **{holdout_actions}** |",
        "",
    ]


def _surprises(C, D) -> list[str]:
    L = ["## 6. Surprises during the replay", "", "| When | What | How it was handled |", "|---|---|---|"]
    for c in C:
        e = c.get("event", {})
        if c["type"] == "title_withdrawn":
            how = (f"{len(c.get('pages_republished', []))} live pages republished without it, "
                   f"{len(c.get('messages_cancelled', []))} messages cancelled")  # fmt: skip
            L.append(f"| {c['at']} | title {e.get('title_id')} withdrawn | {how} |")
        elif c["type"] == "goal_rule_corrected":
            L.append(f"| {c['at']} | {e.get('goal_id')} success rule corrected | new rule version for open "
                     f"{e.get('goal_id')} goals only; no viewer reprocessed |")  # fmt: skip
        elif c["type"].startswith("dependency_"):
            L.append(f"| {c['at']} | {e.get('dependency')}: {e.get('detail')} (until {e.get('until')}) | "
                     "fallbacks, see section 4 |")  # fmt: skip
    reactions = [c for c in C if c["type"] == "reaction_to_live_event"]
    replanned = sum(1 for c in reactions if isinstance(c.get("goal_after"), dict))
    L.append(f"| all day | {len(reactions)} live events changed a viewer's situation (purchase, lapse, opt-out, ...) "
             f"| {replanned} goals re-planned at once, the rest kept |")  # fmt: skip
    faults = Counter((d.get("model") or {}).get("outcome") for d in D)
    shown = {k: faults[k] for k in ("unsupported_claim", "malformed", "error", "unavailable") if faults[k]}
    if shown:
        L.append(
            f"| injected | model faults: {_kv(shown)} | claims never used as evidence; rules-only decision |"
        )
    return [*L, ""]


TRAP_NAMES = {
    "1_duplicate_events": "Duplicate events (same `event_id`)",
    "2_late_events_wrong_clocks": "Late events and wrong phone clocks",
    "3_offline_buffered_app_opens": "Offline-buffered app opens",
    "4_profile_snapshot": "Stale / duplicated profile snapshot",
    "5_new_users_without_profile": "New viewers without a profile row",
    "6_dialect_conflicts": "Dialect conflicts (app / profile / campaign link)",
    "7_language_variants": "Language variants of the same content",
    "8_availability_windows": "Availability windows and withdrawals",
    "9_injected_instructions": "Instructions injected in catalogue text",
    "10_unmeasurable_goals": "Goals with no measurable success",
    "11_unclear_goal_rules": "Goals with unclear rules",
    "12_freshest_source": "Which source is freshest",
    "13_pilot_report": "Pilot report's biased comparison",
}


def _found(key: str, t: dict, q: dict, imp: dict) -> str:
    """What this run's data showed for the trap, from the run's own reports."""
    clk = (q.get("clocks") or {}).get("history") or {}
    dup = (q.get("duplicates") or {}).get("history") or {}
    if key == "1_duplicate_events":
        return (
            f"{dup.get('duplicate_event_ids', 'n/a')} duplicate history events; {t.get('duplicate_triggers_ignored')} "
            f"duplicate triggers, {t.get('second_trigger_same_visit')} second triggers of the same visit"
        )
    if key == "2_late_events_wrong_clocks":
        return (
            f"{clk.get('skewed_clock_users', 'n/a')} viewers with skewed phone clocks (up to "
            f"{clk.get('max_abs_clock_skew_h', 'n/a')} h); {clk.get('buffered_over_1day', 'n/a')} events over a day late"
        )
    if key == "3_offline_buffered_app_opens":
        return f"{t.get('stale_triggers_skipped')} app opens older than {t.get('limit_s')} s"
    if key == "4_profile_snapshot":
        return (
            f"{t.get('users_with_two_rows')} viewers with two rows; {t.get('never_after_paid_contradictions')} "
            "'never' after 'paid' contradictions"
        )
    if key == "5_new_users_without_profile":
        return (
            f"{t.get('trigger_viewers_without_profile')} viewers ({t.get('of_which_signup_event_seen')} with a "
            "signup event)"
        )
    if key == "6_dialect_conflicts":
        return (
            f"{t.get('three_different_dialects')} triggers with three different dialects; "
            f"{t.get('triggers_with_invalid_app_dialect')} with an invalid app dialect"
        )
    if key == "7_language_variants":
        return f"{t.get('slugs_with_several_title_ids')} content slugs with several title ids"
    if key == "8_availability_windows":
        w = t.get("withdrawals") or []
        return f"{t.get('titles_ending_during_replay')} titles ending during the replay; " + "; ".join(
            f"{x['title_id']} withdrawn: {x['pages_republished']} pages republished, "
            f"{x['messages_cancelled']} messages cancelled"
            for x in w
        )
    if key == "9_injected_instructions":
        f = t.get("flagged_titles") or []
        return (
            f"{len(f)} titles ({', '.join(x['title_id'] for x in f)}); used in published actions: "
            f"{sum(x['times_in_published_actions'] for x in f)}"
        )
    if key == "10_unmeasurable_goals":
        off = [g["goal_id"] for g in t.get("goals", []) if not g.get("measurable")]
        return f"not selectable: {', '.join(off) or 'none'}"
    if key == "11_unclear_goal_rules":
        used = t.get("interpretations_used_in_decisions") or {}
        return "; ".join(f"{k} used in {used[k]} decisions" for k in ("[A-G06-1]", "[A-G07-1]") if k in used)
    if key == "12_freshest_source":
        four = (q.get("traps") or {}).get("4_profile_snapshot") or {}
        return f"{four.get('users_with_billing_newer_than_snapshot', 'n/a')} viewers with billing newer than their profile"
    if key == "13_pilot_report":
        pil = imp.get("pilot") or {}
        if pil.get("itt"):
            return (
                f"report headline {_pts(pil['report_headline_served_vs_everyone_else']['difference'])}; "
                f"randomized {_pts(pil['itt']['difference'])}"
            )
    return ""


def _traps(q: dict, imp: dict) -> list[str]:
    traps = q.get("traps") or {}
    L = [
        "## 7. Data issues found and how they were handled",
        "",
        (
            "Counts come from this run (`data_quality_report.json` → `traps`); every handling is proved by the named tests "
            "(`tests/`). Details per trap: [doc/data_traps.md](../doc/data_traps.md)."
        ),
        "",
        "| # | Issue | Found in this run | How it was handled | Proved by |",
        "|---|---|---|---|---|",
    ]
    for key, name in TRAP_NAMES.items():
        t = traps.get(key) or {}
        tests = ", ".join(f"`{x}`" for x in t.get("proved_by", []))
        L.append(
            f"| {key.split('_')[0]} | {name} | {_found(key, t, q, imp)} | {t.get('handling', '')} | {tests} |"
        )
    return [*L, ""]


def _outcomes(O) -> list[str]:
    by = Counter((o["arm"], o["verdict"]) for o in O)
    stages = Counter(o["stage"] for o in O)
    L = [
        "## 8. Goal outcomes",
        "",
        "| Arm | SUCCEEDED | FAILED | INCONCLUSIVE |",
        "|---|---|---|---|",
        *[f"| {arm} | {by[(arm, 'SUCCEEDED')]} | {by[(arm, 'FAILED')]} | {by[(arm, 'INCONCLUSIVE')]} |"
          for arm in ("agent", "holdout")],
        "",
        (f"Verdict stages: {_kv(stages)}. A per-viewer success does not show the agent caused it; only the arm "
        "comparison below measures that. Learning notes are stored per viewer (`outcomes.jsonl`, `viewer_state/`) "
        "and feed the next goal choice (D-051)."),
        "",
    ]  # fmt: skip
    return L


def _impact(imp) -> list[str]:
    p = imp.get("primary", {})
    j = p.get("judged", {})
    if not j:
        return ["## 9. Impact", "", "Not computed (run `report`).", ""]
    sv = imp.get("served_vs_everyone_else", {})
    pil = imp.get("pilot", {})
    L = [
        "## 9. Impact: agent arm vs randomized holdout",
        "",
        (
            f"- **First goal succeeded: agent {_pct(j['agent']['rate'])} ({j['agent']['k']}/{j['agent']['n']}) vs "
            f"holdout {_pct(j['holdout']['rate'])} ({j['holdout']['k']}/{j['holdout']['n']}): "
            f"{_pts(j['difference'])}, {_verdict(j['difference'])}.**"
        ),
    ]
    for seed, s in (imp.get("seeds") or {}).items():
        L.append(f"- Simulator seed {seed}: {_pts(s['difference'])}")
    if sv:
        L.append(f"- The biased served-vs-everyone-else comparison on the same data: {_pts(sv['difference'])}. "
                 "It is not used: who gets served is not random.")  # fmt: skip
    if pil.get("itt"):
        L.append(f"- Earlier pilot re-analysed with its randomized arms: {_pts(pil['itt']['difference'])} "
                 "(its report claimed a large uplift from served vs everyone else).")  # fmt: skip
    return [*L, "", "Full method and tables: `impact_report.md`.", ""]


def _kv(c) -> str:
    return ", ".join(f"{k}: {v}" for k, v in sorted(c.items(), key=lambda kv: -kv[1]))


def write_final(out: Path) -> Path:
    path = Path(out) / "final_report.md"
    path.write_text(build_final(out), encoding="utf-8")
    return path
